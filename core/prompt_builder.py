"""Build LLM prompts for dynamic room generation."""
from __future__ import annotations

from map2d.object_types import ALLOWED_OBJECT_TYPES


def build_intent_prompt(
    room_label: str,
    depth: int,
    occupied: list[str],
    free: list[str],
    remaining: int,
    player_text: str,
) -> str:
    allowed = ", ".join(ALLOWED_OBJECT_TYPES)

    # Depth-specific guidance
    if depth == 0:
        depth_rule = (
            "You are at DEPTH 0 (a street, the root of the world).\n"
            "You can add a BUILDING that the player can walk into:\n"
            "restaurant, shop, cafe, bakery, school, hospital entrance,\n"
            "house, office, library, park, or similar.\n"
            "Do NOT add a room that would only exist inside a building\n"
            "(like a bathroom — that belongs inside a building)."
        )
        example_label = '"Bella\'s Restaurant"'
    elif depth == 1:
        depth_rule = (
            "You are at DEPTH 1 (inside a building).\n"
            "You can ONLY add a ROOM that belongs INSIDE this building:\n"
            "bathroom, kitchen, storage, private dining, office, etc.\n"
            "You must NOT add another building (no hospital, no shop,\n"
            "no restaurant) — that would be semantically wrong.\n"
            "If the player asks for a different building, REJECT with:\n"
            '"You need to go back outside first."'
        )
        example_label = '"Bathroom"'
    else:
        depth_rule = (
            "You are at DEPTH 2 or deeper (a sub-room).\n"
            "You CANNOT add any new door from here.\n"
            "You MUST return action='reject' with a message like:\n"
            '"This is a dead end. Go back first."'
        )
        example_label = '"Room"'

    return (
        "You are the room generator for a 2D life-simulation game.\n\n"
        "OUTPUT (JSON only, no commentary, no markdown):\n"
        "{\n"
        '  "action": "add_door" | "reject",\n'
        '  "direction": "north" | "south" | "east" | "west",\n'
        '  "label": "<short name, 2-5 words>",\n'
        '  "message": "<one sentence, max 20 words>",\n'
        '  "room_spec": {\n'
        '    "floor_color": [r, g, b],\n'
        '    "wall_color": [r, g, b],\n'
        '    "spawn": [x, y],\n'
        '    "objects": [{"type": "<allowed>", "x": int, "y": int}]\n'
        "  }\n"
        "}\n\n"
        f"ALLOWED OBJECT TYPES:\n{allowed}\n\n"
        "ROOM GRID: 15 wide x 10 tall.\n"
        "Coordinate range: x in [1, 13], y in [1, 8].\n"
        "Outer walls and the door are auto-generated by code.\n\n"
        "ROOM DESIGN RULES:\n"
        "- spawn: where the player appears. Must be a free interior tile.\n"
        "- objects: 4 to 15 items. No overlaps. Do not place on spawn.\n"
        "- Leave a clear 3-tile-wide path from the door.\n"
        f"- Label like {example_label}, human-readable.\n"
        "- Pick colors matching the mood of the room.\n\n"
        "=====  TREE DEPTH RULE  =====\n"
        f"{depth_rule}\n"
        "=============================\n\n"
        "GENERAL REJECT RULES:\n"
        "- Vague intent -> reject.\n"
        "- Implausible for this location -> reject.\n"
        "- Rejection is normal; do not force add_door.\n\n"
        f"CURRENT ROOM: \"{room_label}\" (depth {depth})\n"
        f"Occupied door directions: {occupied or ['none']}\n"
        f"Free door directions: {free or ['none']}\n"
        f"Rooms remaining until cap: {remaining}\n\n"
        f'PLAYER INTENT:\n"{player_text}"\n\n'
        "Return JSON only.\n"
    )